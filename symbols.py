def _image_file(code):
    """Image file name in static/symbols for a symbol code."""
    offset = ord(code[1]) - 32
    if code[0] == "/":
        return f"symbols{offset:03d}.png"
    return f"symbols{2000 + offset}.png"


SYMBOLS = [
    {"code": code, "table": "primary" if code[0] == "/" else "alternate",
     "file": _image_file(code), "names": {"en": en, "de": de}, "keywords": _KEYWORDS.get(code, "")}
    for code, en, de in _SYMBOLS
]

SYMBOLS_BY_CODE = {s["code"]: s for s in SYMBOLS}


def symbol_image(code):
    """Image file for any valid two-character code, also ones not offered in the picker."""
    if isinstance(code, str) and len(code) == 2 and code[0] in "/\\" and 0x21 <= ord(code[1]) <= 0x7D:
        return _image_file(code)
    return None
